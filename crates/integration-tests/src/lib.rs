use network_core::{
    observation::{ObservationId, PacketObservation},
    packet::Packet,
    BackendSource, Direction, Timestamp,
};

/// Shared deterministic packet used by integration coverage.
pub fn sample_observation(id: u64) -> PacketObservation {
    let now = Timestamp::now();
    PacketObservation::new(
        ObservationId::new(id), BackendSource::WinDivert, now, now,
        Direction::Inbound, "integration0", Packet::new(sample_ipv4_tcp_packet()),
    )
}

/// Ethernet + IPv4 + TCP packet with stable addresses and ports.
pub fn sample_ipv4_tcp_packet() -> Vec<u8> {
    vec![
        0x00,0x11,0x22,0x33,0x44,0x55, 0x66,0x77,0x88,0x99,0xaa,0xbb,
        0x08,0x00, 0x45,0x00,0x00,0x28,0x00,0x01,0x00,0x00,0x40,0x06,0x00,0x00,
        0xc0,0xa8,0x01,0x01, 0xc0,0xa8,0x01,0x02,
        0x00,0x50,0x1f,0x90, 0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,
        0x50,0x02,0x20,0x00,0x00,0x00,0x00,0x00,
    ]
}
